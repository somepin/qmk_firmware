bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {
        oled_timer = timer_read();
        if (!is_oled_on()) {
            oled_on();
        }
        pop();
    }
    return true;
}

void render_mod_status(uint8_t modifiers) {
    oled_set_cursor(0,3);
    oled_write_char('G', (modifiers & MOD_MASK_GUI));
    oled_write_char('A', (modifiers & MOD_MASK_ALT));
    oled_write_char('C', (modifiers & MOD_MASK_CTRL));
    oled_write_char('S', (modifiers & MOD_MASK_SHIFT));
}

void oled_render_layer_state(void) {
    oled_set_cursor(0,0);
    oled_write_P(PSTR("Mode:"), false);
    oled_set_cursor(0,1);
    switch (get_highest_layer(layer_state)) {  
        case _BASE:
            oled_write_P(PSTR("CmkDH"), false); 
            break;
        case _QWERTY:
            oled_write_P(PSTR("QWERT"), false); 
            break;
        case _NAV:
            oled_write_P(PSTR("Navi "), false); 
            break;
        case _LOWER:
            oled_write_P(PSTR("Lower"), false);
            break;
        case _RAISE:
            oled_write_P(PSTR("Raise"), false);
            break;
        case _ADJUST:
            oled_write_P(PSTR("Adjst"), false);
            break;
    }
}

